#!/usr/bin/env python3
"""Build js/script.js from script/script.md — every word the player reads, one entry per `###` slot.

A slot is a `### key` heading (anything after the key on that line is a note for the writer) and the text
under it up to the next heading. The text is trimmed; its line breaks and paragraph breaks become single
spaces; `---` rules are dropped. A duplicate key or an empty slot stops the build. The game has no build
step at run time, so js/script.js is committed; tools/tests/test_build_script.py fails when it is stale.

    python3 tools/build_script.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'script', 'script.md')
OUT = os.path.join(ROOT, 'js', 'script.js')

HEADING = re.compile(r'^#{1,6}\s')
SLOT = re.compile(r'^###\s+(\S+)')
RULE = re.compile(r'^\s*-{3,}\s*$')


class ScriptError(ValueError):
    pass


def parse(text):
    """{key: text} for every `### key` slot, in document order."""
    slots, key, lines = {}, None, []

    def close():
        if key is None:
            return
        body = ' '.join(l.strip() for l in lines if l.strip() and not RULE.match(l))
        if not body:
            raise ScriptError(f'empty slot: {key}')
        slots[key] = body

    for line in text.splitlines():
        if HEADING.match(line):
            close()
            key, lines = None, []
            m = SLOT.match(line)
            if m:
                key = m.group(1)
                if key in slots:
                    raise ScriptError(f'duplicate slot: {key}')
            continue
        if key is not None:
            lines.append(line)
    close()
    return slots


def render(slots):
    body = json.dumps(slots, ensure_ascii=False, indent=2)
    return ('// GENERATED by tools/build_script.py from script/script.md — edit the script, then rebuild.\n'
            f'export const SCRIPT = {body};\n')


def main():
    with open(SRC, encoding='utf-8') as f:
        slots = parse(f.read())
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(render(slots))
    print(f'{len(slots)} slots -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    try:
        main()
    except ScriptError as e:
        sys.exit(f'build_script: {e}')
