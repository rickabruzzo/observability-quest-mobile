import json
import re

import pytest

from tools import build_script as bs

DOC = """# Title

Intro prose that belongs to no slot.

## Section

Section prose, also no slot.

### a.one
First line.

### a.two — a note after the key
Two lines
that join.

Second paragraph.

---

## Next section

### b.one
[Bracketed prompt]
"""


def test_parse_takes_one_entry_per_slot_with_text_trimmed_and_lines_joined():
    assert bs.parse(DOC) == {
        'a.one': 'First line.',
        'a.two': 'Two lines that join. Second paragraph.',
        'b.one': '[Bracketed prompt]',
    }


def test_duplicate_key_fails_loudly():
    with pytest.raises(bs.ScriptError, match='a.one'):
        bs.parse('### a.one\nx\n\n### a.one\ny\n')


def test_empty_slot_fails_loudly():
    with pytest.raises(bs.ScriptError, match='a.empty'):
        bs.parse('### a.empty\n\n---\n\n### a.full\nx\n')


def test_render_is_an_es_module_whose_object_round_trips():
    src = bs.render({'k.1': 'He said "hi" — it’s fine', 'k.2': 'x'})
    assert src.startswith('// GENERATED by tools/build_script.py')
    body = re.search(r'export const SCRIPT = (\{.*\});', src, re.S).group(1)
    assert json.loads(body) == {'k.1': 'He said "hi" — it’s fine', 'k.2': 'x'}


def test_committed_script_js_matches_the_markdown():
    # A script edit without a rebuild fails here: run `python3 tools/build_script.py`.
    with open(bs.SRC, encoding='utf-8') as f:
        expected = bs.render(bs.parse(f.read()))
    with open(bs.OUT, encoding='utf-8') as f:
        assert f.read() == expected, 'js/script.js is stale: run python3 tools/build_script.py'


def test_the_real_script_has_every_chapter_one_and_menu_slot():
    with open(bs.SRC, encoding='utf-8') as f:
        script = bs.parse(f.read())
    for k in ['menu.title', 'menu.hint', 'menu.done', 'after.prompt', 'after.claim', 'after.more',
              'ch1.card.title', 'ch1.room.enter', 'ch1.hc.step2.result', 'ch1.verdict', 'help.window']:
        assert script.get(k), k
    for n in range(1, 6):
        assert script.get(f'menu.ch{n}.name') and script.get(f'menu.ch{n}.hook')
